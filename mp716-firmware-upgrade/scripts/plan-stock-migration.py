#!/usr/bin/env python3
"""Create a private stock-014 migration plan offline. Never applies it or flashes."""

from __future__ import annotations

import argparse
import hashlib
import io
import ipaddress
import json
import re
import shlex
import tarfile
from pathlib import Path


def parse_uci(text):
    sections = []
    for line in text.splitlines():
        words = shlex.split(line, comments=True)
        if not words:
            continue
        if words[0] == 'package' and len(words) == 2:
            continue
        if words[0] == 'config' and len(words) in (2, 3):
            sections.append({'type': words[1], 'name': words[2] if len(words) == 3 else '', 'options': {}})
        elif words[0] in ('option', 'list') and len(words) == 3 and sections:
            options = sections[-1]['options']
            if words[0] == 'list':
                options.setdefault(words[1], []).append(words[2])
            else:
                options[words[1]] = words[2]
        else:
            raise ValueError('Unsupported UCI syntax in backup')
    return sections


def section(configs, package, name=None, kind=None):
    found = [s['options'] for s in configs.get(package, [])
             if (name is None or s['name'] == name) and (kind is None or s['type'] == kind)]
    if len(found) != 1:
        raise ValueError(f'Expected one {package} section: {name or kind}')
    return found[0]


def quote(value):
    value = str(value)
    if any(ord(c) < 32 or ord(c) == 127 for c in value):
        raise ValueError('Control characters are not allowed in migrated values')
    return "'" + value.replace("'", "'\\''") + "'"


def plan(configs):
    """Whitelist the measured wired-router configuration; reject unsupported use."""
    blocked = []
    for package in ('ddns', 'ppl2tp', 'pptpd', 'xl2tpd', 'openvpn'):
        if any(s['options'].get('enable', s['options'].get('enabled', '0')) == '1'
               for s in configs.get(package, [])):
            blocked.append(package)
    if any(s['options'].get('qos_mode', '0') != '0' for s in configs.get('huayi_qos', [])):
        blocked.append('QoS')
    mode = section(configs, 'system', 'mode')
    if mode.get('wan_type') != 'wired' or mode.get('opmode') != '0':
        blocked.append('non-wired-router-mode')
    legacy_fw = configs.get('huayi_firewall', [])
    for s in legacy_fw:
        for key in ('url_filter', 'port_forward', 'conn_limit', 'acl_count', 'dmz_enable'):
            if s['options'].get(key, '0') != '0':
                blocked.append('firewall-' + key)
    if blocked:
        raise ValueError('Active features need explicit adaptation: ' + ', '.join(sorted(set(blocked))))

    wan = section(configs, 'network', 'wan')
    lan = section(configs, 'network', 'lan')
    if wan.get('proto') != 'dhcp' or wan.get('ifname') != 'eth0.2' or lan.get('ifname') != 'eth0.1':
        raise ValueError('Only the audited eth0.1 LAN / eth0.2 DHCP WAN topology is supported')
    subnet = ipaddress.IPv4Interface(lan['ipaddr'] + '/' + lan['netmask'])
    if subnet.network.prefixlen != 24:
        raise ValueError('DHCP range migration currently requires a /24 LAN')
    dhcp = section(configs, 'dhcp', 'lan')
    start, limit = int(dhcp['start']), int(dhcp['limit'])
    router = int(subnet.ip) - int(subnet.network.network_address)
    end = start + limit - 1
    if start == router:
        start += 1
    if end == router:
        end -= 1
    if not 1 <= start <= end <= 254 or start <= router <= end:
        raise ValueError('DHCP pool cannot include the router address')

    commands = []

    def set_(key, value):
        if isinstance(value, list):
            commands.append('delete ' + key)
            commands.extend('add_list ' + key + '=' + quote(v) for v in value)
        else:
            commands.append('set ' + key + '=' + quote(value))

    set_('network.lan.ipaddr', str(subnet))
    commands.append('delete network.lan.netmask')
    # Keep the switch and device sections generated by board detection.
    set_('network.lan.device', 'br-lan')
    set_('network.wan.device', 'eth0.2')
    set_('network.wan.proto', 'dhcp')
    for name, source in (('lan', lan), ('wan', wan)):
        mac = source.get('macaddr', '')
        if not re.fullmatch(r'(?:[0-9a-fA-F]{2}:){5}[0-9a-fA-F]{2}', mac) or int(mac[:2], 16) & 1:
            raise ValueError('Invalid source network MAC')
        set_('network.' + name + '.macaddr', mac.lower())
    for key in ('hostname', 'mtu', 'peerdns', 'dns', 'metric'):
        if key in wan:
            set_('network.wan.' + key, wan[key])
    if not 576 <= int(wan.get('mtu', '1500')) <= 1500:
        raise ValueError('Invalid WAN MTU')
    set_('dhcp.lan.ignore', dhcp.get('ignore', '0'))
    set_('dhcp.lan.start', start)
    set_('dhcp.lan.limit', end - start + 1)
    set_('dhcp.lan.leasetime', dhcp.get('leasetime', '7200'))
    dnsmasq = [s['options'] for s in configs.get('dhcp', []) if s['type'] == 'dnsmasq']
    if len(dnsmasq) > 1:
        raise ValueError('Multiple dnsmasq instances need separate adaptation')
    if dnsmasq:
        for key in ('domainneeded', 'boguspriv', 'filterwin2k', 'localise_queries',
                    'rebind_protection', 'rebind_localhost', 'local', 'domain',
                    'expandhosts', 'nonegcache', 'authoritative', 'readethers', 'localservice'):
            if key in dnsmasq[0]:
                set_('dhcp.@dnsmasq[0].' + key, dnsmasq[0][key])
    hosts = [s['options'] for s in configs.get('dhcp', []) if s['type'] == 'host']
    for index, host in enumerate(hosts):
        if ipaddress.IPv4Address(host['ip']) not in subnet.network or host['ip'] == str(subnet.ip):
            raise ValueError('Static DHCP lease conflicts with LAN')
        prefix = 'dhcp.mp716_stock_' + str(index)
        set_(prefix, 'host')
        for key in ('ip', 'mac', 'name', 'dns'):
            if key in host:
                set_(prefix + '.' + key, host[key])
        set_(prefix + '.leasetime', 'infinite' if host.get('leasetime') == '0' else host.get('leasetime', '7200'))

    radios = [s for s in configs.get('wireless', []) if s['type'] == 'wifi-device']
    aps = [s for s in configs.get('wireless', []) if s['type'] == 'wifi-iface' and s['options'].get('disabled', '0') == '0']
    if len(radios) != 1 or len(aps) != 1 or aps[0]['options'].get('mode') != 'ap':
        raise ValueError('Multiple radios/APs or an enabled Wi-Fi client need separate adaptation')
    radio, ap = radios[0]['options'], aps[0]['options']
    if ap.get('encryption') not in ('psk2+ccmp', 'psk-mixed+ccmp', 'psk2', 'psk-mixed'):
        raise ValueError('Unsupported Wi-Fi encryption')
    if ap.get('macfilterenable', '0') != '0' or ap.get('network') != 'lan':
        raise ValueError('Wi-Fi ACL or non-LAN AP needs separate adaptation')
    if not 1 <= len(ap['ssid'].encode()) <= 32 or not (8 <= len(ap['key']) <= 63 or re.fullmatch(r'[a-fA-F0-9]{64}', ap['key'])):
        raise ValueError('Invalid Wi-Fi SSID or PSK')
    set_('wireless.radio0.disabled', radio.get('disabled', '0'))
    set_('wireless.radio0.country', radio.get('country', 'CN'))
    set_('wireless.radio0.channel', radio.get('channel', 'auto'))
    set_('wireless.radio0.htmode', 'HT20')
    set_('wireless.default_radio0', 'wifi-iface')
    for key, value in {'device': 'radio0', 'network': 'lan', 'mode': 'ap', 'disabled': '0',
                       'ssid': ap['ssid'], 'key': ap['key'], 'encryption': ap['encryption'],
                       'hidden': ap.get('hidden', '0'), 'isolate': ap.get('noforward', '0')}.items():
        set_('wireless.default_radio0.' + key, value)

    system = section(configs, 'system', kind='system')
    for key in ('hostname', 'timezone', 'log_size'):
        if key in system:
            set_('system.@system[0].' + key, system[key])
    ntp = section(configs, 'system', 'ntp')
    for key in ('enabled', 'enable_server', 'server'):
        if key in ntp:
            set_('system.ntp.' + key, ntp[key])
    upnp = section(configs, 'upnpd', 'config')
    set_('upnpd.config.enabled', '1' if upnp.get('enable_upnp') == '1' or upnp.get('enable_natpmp') == '1' else '0')
    for key in ('enable_upnp', 'enable_natpmp', 'secure_mode', 'log_output', 'port', 'download', 'upload', 'uuid'):
        if key in upnp:
            set_('upnpd.config.' + key, upnp[key])
    set_('upnpd.config.external_iface', 'wan')
    set_('upnpd.config.internal_iface', 'lan')
    # Replace the two upstream default permission rules in the same order.
    permissions = [s['options'] for s in configs['upnpd'] if s['type'] == 'perm_rule']
    if len(permissions) != 2:
        raise ValueError('Custom UPnP permission rule layout needs separate adaptation')
    for index, permission in enumerate(permissions):
        for key in ('action', 'ext_ports', 'int_addr', 'int_ports', 'comment'):
            if key in permission:
                set_(f'upnpd.@perm_rule[{index}].' + key, permission[key])
    # Keep firewall4 LAN->WAN forwarding, masquerading, and WAN default rejection.
    # Preserve only the explicitly enabled stock remote HTTP management exception.
    remote = section(configs, 'huayi_firewall', 'remote')
    remote_http = remote.get('remote_enable') == '1'
    if remote_http:
        if remote.get('port') != '80':
            raise ValueError('Nonstandard remote-management port needs separate adaptation')
        for key, value in {'': 'rule', '.name': 'Stock-014-HTTP-management', '.src': 'wan',
                           '.proto': 'tcp', '.dest_port': '80', '.target': 'ACCEPT', '.family': 'ipv4'}.items():
            set_('firewall.mp716_stock_http' + key, value)
    wanping = [s['options'] for s in legacy_fw if s['name'] == 'wanping']
    if wanping and wanping[0].get('wanping_en') == '0':
        # The fixed firewall4 defaults name their second rule Allow-Ping.
        set_('firewall.@rule[1].enabled', '0')
    for package in ('network', 'dhcp', 'wireless', 'system', 'upnpd', 'firewall'):
        commands.append('commit ' + package)
    report = {'status': 'UNVERIFIED', 'wan_protocol': 'dhcp', 'wan_device': 'eth0.2',
              'wan_mtu': int(wan.get('mtu', '1500')), 'lan_device': 'br-lan',
              'static_leases': len(hosts), 'wifi_credentials_preserved': True,
              'wifi_htmode': 'HT20', 'upnp_enabled': upnp.get('enable_upnp') == '1',
              'stock_wan_http_management_preserved': remote_http,
              'unadapted_inactive_features': ['VPN', 'QoS', 'DDNS', '4G'],
              'configuration_applied': False, 'flash_write': False}
    return '\n'.join(commands) + '\n', report


def load_backup(path):
    configs, shadow = {}, None
    with tarfile.open(path, 'r:gz') as archive:
        total = 0
        seen = set()
        for member in archive:
            total += member.size
            if total > 4 * 1024 * 1024:
                raise ValueError('Backup is too large')
            name = member.name.removeprefix('./')
            if name in seen:
                raise ValueError('Duplicate backup path')
            seen.add(name)
            relevant = name.startswith('etc/config/') and len(name.split('/')) == 3 or name == 'etc/shadow'
            if not relevant:
                continue
            if not member.isfile() or member.size > 256 * 1024:
                raise ValueError('Invalid backup member')
            data = archive.extractfile(member).read().decode('utf-8')
            if name == 'etc/shadow':
                shadow = next((line.split(':')[1] for line in data.splitlines() if line.startswith('root:')), None)
            else:
                configs[name.rsplit('/', 1)[-1]] = parse_uci(data)
    if not shadow or not re.fullmatch(r'\$(?:1|5|6)\$[A-Za-z0-9$./=,-]+', shadow):
        raise ValueError('A supported root password hash is required')
    return configs, shadow


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('backup', type=Path)
    parser.add_argument('--output', required=True, type=Path)
    args = parser.parse_args()
    configs, shadow = load_backup(args.backup)
    batch, report = plan(configs)
    args.output.mkdir(parents=True, exist_ok=False, mode=0o700)
    for name, data in {'migration.uci': batch, 'root-password.hash': shadow + '\n'}.items():
        path = args.output / name
        path.write_text(data, encoding='utf-8', newline='\n')
        path.chmod(0o600)
    report['backup_sha256'] = hashlib.sha256(args.backup.read_bytes()).hexdigest()
    # A private OpenWrt config-restore archive, not an image or stock upload file.
    installer = Path(__file__).resolve().parents[1] / 'integration/migration/99-mp716-stock-014'
    archive_path = args.output / 'mp716-stock-014-migration.tar.gz'
    with tarfile.open(archive_path, 'w:gz') as archive:
        for name, data, mode in (
            ('etc/mp716-migration/migration.uci', batch.encode(), 0o600),
            ('etc/mp716-migration/root-password.hash', (shadow + '\n').encode(), 0o600),
            ('etc/uci-defaults/99-mp716-stock-014', installer.read_bytes().replace(b'\r\n', b'\n'), 0o700),
        ):
            member = tarfile.TarInfo(name)
            member.size, member.mode = len(data), mode
            archive.addfile(member, io.BytesIO(data))
    archive_path.chmod(0o600)
    report['migration_archive_sha256'] = hashlib.sha256(archive_path.read_bytes()).hexdigest()
    (args.output / 'migration-report.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(report))


if __name__ == '__main__':
    main()
